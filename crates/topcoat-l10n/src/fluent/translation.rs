use std::{borrow::Cow, hint};

use topcoat_core::{context::Cx, cursor::ConstReader};
#[cfg(feature = "view")]
use topcoat_view::{AttributeValueViewParts, NodeViewParts, PartsWriter};

use crate::{Argument, Locale, Namespace, RawTranslation, try_locale};

/// A Fluent message or attribute together with the arguments needed to translate it.
///
/// You can create a translation without a [`Cx`]. Formatting happens when it is
/// [resolved](Self::resolve), using the locale at that point. In a view, it displays
/// the resolved text as content or as an attribute value.
#[derive(Clone)]
pub struct Translation<'a> {
    namespace: &'static str,
    id: &'static str,
    attribute: Option<&'static str>,
    args: Box<[(&'static str, Argument<'a>)]>,
}

impl<'a> Translation<'a> {
    /// Creates a translation from a [`RawTranslation`] record and its named arguments.
    ///
    /// # Panics
    ///
    /// Panics if the record is invalid. Records generated by `t!` are valid.
    #[doc(hidden)]
    #[must_use]
    pub fn new(record: &'static [u8], args: Box<[(&'static str, Argument<'a>)]>) -> Self {
        // Tools find `t!` calls by searching the binary for their records.
        // Reading through `black_box` keeps the optimizer from removing them.
        let record = hint::black_box(record);
        let (namespace, id, attribute) = RawTranslation::decode_key(&mut ConstReader::new(record))
            .expect("the translation record is valid");
        Self {
            namespace,
            id,
            attribute,
            args,
        }
    }

    /// Returns the message text using the [locale](try_locale) stored in `cx`.
    ///
    /// Uses the same rules as [`resolve_in`](Self::resolve_in). If the context has no
    /// locale, returns a placeholder containing the key and arguments.
    #[must_use]
    pub fn resolve(&self, cx: &Cx) -> Cow<'static, str> {
        match try_locale(cx) {
            Some(locale) => self.resolve_in(locale),
            None => Cow::Owned(self.placeholder()),
        }
    }

    /// Returns the message text for `locale` using
    /// [`Catalog::format`](crate::Catalog::format).
    ///
    /// If the message is unavailable, returns its key and arguments as a placeholder,
    /// such as `password-field.placeholder(min = 8)`. String arguments appear in
    /// quotes. Numbers appear without locale formatting.
    ///
    /// Borrows the text from the catalog when no formatting is needed.
    #[must_use]
    pub fn resolve_in(&self, locale: &Locale) -> Cow<'static, str> {
        Namespace::catalog(self.namespace)
            .and_then(|catalog| catalog.format(locale, self.id, self.attribute, &self.args))
            .unwrap_or_else(|| Cow::Owned(self.placeholder()))
    }

    /// Builds a placeholder from the key and arguments for a missing translation.
    fn placeholder(&self) -> String {
        let mut text = String::from(self.id);
        if let Some(attribute) = self.attribute {
            text.push('.');
            text.push_str(attribute);
        }
        for (index, (name, value)) in self.args.iter().enumerate() {
            text.push_str(if index == 0 { "(" } else { ", " });
            text.push_str(name);
            text.push_str(" = ");
            value.write_placeholder(&mut text);
        }
        if !self.args.is_empty() {
            text.push(')');
        }
        text
    }

    /// Resolves the translation and appends its escaped text to the view.
    #[cfg(feature = "view")]
    fn push(&self, cx: &Cx, parts: &mut PartsWriter<'_>) {
        match self.resolve(cx) {
            Cow::Borrowed(text) => parts.push_static_str(text),
            Cow::Owned(text) => parts.push_string(text),
        };
    }
}

/// Displays a translation as escaped text in a view.
#[cfg(feature = "view")]
impl NodeViewParts for Translation<'_> {
    fn into_view_parts(self, cx: &Cx, parts: &mut PartsWriter<'_>) {
        self.push(cx, parts);
    }
}

/// Displays a translation in an attribute value, as in
/// `placeholder=(t!(login-input.placeholder))`.
#[cfg(feature = "view")]
impl AttributeValueViewParts for Translation<'_> {
    fn attribute_present(&self) -> bool {
        true
    }

    fn into_view_parts(self, cx: &Cx, parts: &mut PartsWriter<'_>) {
        self.push(cx, parts);
    }
}

#[cfg(test)]
mod tests {
    use http::{Request, header::ACCEPT_LANGUAGE};
    use topcoat::view::{View, ViewExt, view};

    use super::*;
    use crate::{
        FluentType, NamespaceLocale, locale, test_namespace_record, test_translation_record,
    };

    const NAMESPACE: &str = "translation";

    inventory::submit! {
        Namespace::new(
            test_namespace_record!(NAMESPACE),
            &[
                NamespaceLocale::new(
                    "en",
                    &["\
title = Welcome
greeting = Hello, { $name }!
login-input = Log in
    .placeholder = Your name
"],
                ),
                NamespaceLocale::new(
                    "de",
                    &["\
title = Willkommen
greeting = Hallo, { $name }!
"],
                ),
            ],
        )
    }

    fn title() -> Translation<'static> {
        Translation::new(
            test_translation_record!(NAMESPACE, "title", None),
            Box::new([]),
        )
    }

    /// Creates a request context with the given `Accept-Language` header.
    fn request(header: &str) -> Cx {
        let (parts, ()) = Request::builder()
            .header(ACCEPT_LANGUAGE, header)
            .body(())
            .expect("request should build")
            .into_parts();
        Cx::default().with(parts)
    }

    #[test]
    fn resolves_for_the_locale_of_the_scope() {
        let cx = Cx::default().with(locale!("de"));
        assert_eq!(title().resolve(&cx), "Willkommen");
    }

    #[test]
    fn resolves_in_a_locale_other_than_the_one_of_the_scope() {
        let title = title();
        let cx = Cx::default().with(locale!("en"));
        assert_eq!(title.resolve(&cx), "Welcome");
        assert_eq!(title.resolve_in(&locale!("de")), "Willkommen");
        assert_eq!(title.resolve_in(&locale!("fr")), "title");
    }

    #[test]
    fn a_locale_the_catalog_lacks_resolves_to_the_placeholder_instead_of_using_the_header() {
        // The page is in French, so the German the header asks for would be
        // out of place.
        let cx = request("de").with(locale!("fr"));
        assert_eq!(title().resolve(&cx), "title");
    }

    #[test]
    fn resolves_to_the_placeholder_without_a_locale() {
        let cx = request("de");
        assert_eq!(title().resolve(&cx), "title");
    }

    #[test]
    fn resolves_to_the_placeholder_for_an_unknown_namespace() {
        let title = Translation::new(
            test_translation_record!("unknown", "title", None),
            Box::new([]),
        );
        let cx = Cx::default().with(locale!("en"));
        assert_eq!(title.resolve(&cx), "title");
    }

    #[test]
    fn the_placeholder_shows_the_key_and_the_arguments() {
        let missing = Translation::new(
            test_translation_record!(NAMESPACE, "missing", Some("label")),
            Box::new([
                ("name", Argument::from("Ada")),
                ("count", Argument::from(8)),
            ]),
        );
        let cx = Cx::default().with(locale!("en"));
        assert_eq!(
            missing.resolve(&cx),
            r#"missing.label(name = "Ada", count = 8)"#
        );
    }

    #[test]
    fn formats_borrowed_arguments() {
        let name = String::from("Ada");
        let greeting = Translation::new(
            test_translation_record!(NAMESPACE, "greeting", None),
            Box::new([("name", Argument::from(&name))]),
        );
        let cx = Cx::default().with(locale!("de"));
        // Fluent isolates the argument from the surrounding text.
        assert_eq!(greeting.resolve(&cx), "Hallo, \u{2068}Ada\u{2069}!");
    }

    #[test]
    fn formats_custom_arguments() {
        #[derive(Debug, PartialEq)]
        struct Name;

        impl FluentType for Name {
            fn duplicate(&self) -> Box<dyn FluentType + Send> {
                Box::new(Self)
            }

            fn as_string(&self, _: &intl_memoizer::IntlLangMemoizer) -> Cow<'static, str> {
                Cow::Borrowed("Ada")
            }

            fn as_string_threadsafe(
                &self,
                _: &intl_memoizer::concurrent::IntlLangMemoizer,
            ) -> Cow<'static, str> {
                Cow::Borrowed("Ada")
            }
        }

        let greeting = Translation::new(
            test_translation_record!(NAMESPACE, "greeting", None),
            Box::new([("name", Argument::custom(Name))]),
        );
        let cx = Cx::default().with(locale!("en"));
        assert_eq!(greeting.resolve(&cx), "Hello, \u{2068}Ada\u{2069}!");
    }

    #[test]
    fn can_be_shared_between_threads_and_cloned() {
        fn check<T: Send + Sync + Clone>() {}
        check::<Translation<'_>>();
    }

    #[test]
    fn borrows_text_without_arguments() {
        let cx = Cx::default().with(locale!("en"));
        assert!(matches!(title().resolve(&cx), Cow::Borrowed(_)));
    }

    async fn render(view: impl View, cx: &Cx) -> String {
        view.single().await.unwrap().render(cx)
    }

    #[tokio::test]
    async fn renders_as_escaped_content() {
        let greeting = Translation::new(
            test_translation_record!(NAMESPACE, "greeting", None),
            Box::new([("name", Argument::from("<b>"))]),
        );
        let cx = &Cx::default().with(locale!("en"));
        let html = render(view! { cx => <p>(greeting)</p> }, cx).await;
        assert_eq!(html, "<p>Hello, \u{2068}&lt;b&gt;\u{2069}!</p>");
    }

    #[tokio::test]
    async fn renders_as_an_attribute_value() {
        let placeholder = Translation::new(
            test_translation_record!(NAMESPACE, "login-input", Some("placeholder")),
            Box::new([]),
        );
        let cx = &Cx::default().with(locale!("en"));
        let html = render(view! { cx => <input placeholder=(placeholder)> }, cx).await;
        assert_eq!(html, r#"<input placeholder="Your name">"#);
    }
}
